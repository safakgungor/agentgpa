/**
 * Laughter has no fixed length ("hahaha", "jajaja", "kkkk"), so it is the one pattern here:
 * repeated laugh syllables and the usual abbreviations, as whole words.
 */
export const LAUGH =
  /(?<![\p{L}\p{N}])(?:a?(?:ha){2,}h?|(?:he){2,}h?|(?:hi){2,}|(?:ja){2,}|(?:je){2,}|k{4,}|lo+l|lmf?ao+|rofl|mdr+|xd+|ptdr)(?![\p{L}\p{N}])/u;

/**
 * Lowercase that treats the four Turkish I letters (I, ı, İ, i) as one, so "HAYIR" matches
 * "hayır" and "TEŞEKKÜRLER" matches "teşekkürler" in every locale. Curly apostrophes become
 * straight ones.
 */
export function fold(text: string): string {
  return text.normalize('NFC').replace(/[İIı]/g, 'i').toLowerCase().replace(/[‘’ʼ]/g, "'");
}

const escapeRegex = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** One regex for a lexicon, longest phrases first, bounded by non-letters. */
export function compile(lexicon: Lexicon): RegExp {
  const words = [...new Set(lexicon.words.map(fold))]
    .sort((a, b) => b.length - a.length)
    .map(escapeRegex);
  const body = `(?:${words.join('|')})(?![\\p{L}\\p{N}])`;
  if (lexicon.whole) return new RegExp(`^[\\s\\p{P}]*${body}[\\s\\p{P}]*$`, 'u');
  return new RegExp(lexicon.atStart ? `^[\\s\\p{P}]*${body}` : `(?<![\\p{L}\\p{N}])${body}`, 'u');
}

