// The fixture scrubber. It keeps structure (keys, types, nesting, line kinds, ids and their
// links, timing, lengths, whitespace, case and punctuation) and replaces all text with
// synthetic words. A random key per run drives every replacement, so the output cannot be
// matched against guesses. Only fixed client markers (tags such as <command-name> and phrases
// such as "[Request interrupted by user]") and structural values survive. Inside free text,
// emails, URLs, domains, absolute paths, time zones and the names it is given are replaced
// whole by fixed placeholders: a shape kept letter by letter (lengths, digits, dots) can be
// matched against a guess, so they keep none. Money values become 0, and token counts and
// durations keep two significant digits.

